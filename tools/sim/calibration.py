"""Sim calibration hooks (docs/engineering/18 §"calibration").

Doc 18: "parameters calibrated against real data once Phase 1 produces
any." The sim's hand-tuned constants are reasonable defaults; once a
Darwin runs in production, calibration data points (real LLM costs,
real affiliate payouts, real captcha frequency) feed back into the sim
so the next mutation candidate is evaluated against numbers that
match the world.

This module ships:

- :class:`CalibrationDataset` — a structured record of observed
  values per metric, with provenance + ts.
- :class:`SimCalibration` — applies a dataset to a :class:`SimWorld`
  by overriding the relevant constants. Built-in support for
  ``compute_usd_per_day``, ``revenue_usd_per_effective_piece``,
  and the captcha cadence.

The calibration object is a *capability*, not a side-channel: it
overrides the sim's parameters explicitly and audibly. Production
deployers wire it from a JSON file generated by the supervisor's
billing service + the operator audit log."""

from __future__ import annotations

import json
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path


@dataclass(frozen=True)
class CalibrationPoint:
    """One measured value from production. Carries provenance so a
    re-run can verify the same input."""

    metric: str
    value: float
    source: str           # "audit:darwin-d-1" / "billing:fleet" / etc.
    observed_at: float


@dataclass
class CalibrationDataset:
    """Collection of points + the timeline they cover. The sim picks
    the most recent point per metric (one value per knob, not a
    series)."""

    points: list[CalibrationPoint] = field(default_factory=list)

    def add(
        self,
        *,
        metric: str,
        value: float,
        source: str,
        observed_at: float | None = None,
    ) -> None:
        self.points.append(CalibrationPoint(
            metric=metric, value=float(value), source=source,
            observed_at=observed_at if observed_at is not None else time.time(),
        ))

    def latest(self, metric: str) -> CalibrationPoint | None:
        rows = [p for p in self.points if p.metric == metric]
        if not rows:
            return None
        return max(rows, key=lambda p: p.observed_at)

    def to_json(self) -> dict:
        return {"points": [asdict(p) for p in self.points]}

    @classmethod
    def from_json(cls, data: dict) -> "CalibrationDataset":
        ds = cls()
        for raw in data.get("points", []):
            ds.points.append(CalibrationPoint(**raw))
        return ds

    @classmethod
    def from_file(cls, path: str | Path) -> "CalibrationDataset":
        data = json.loads(Path(path).read_text())
        return cls.from_json(data)


# The metric names the calibration recognises. Each maps to a sim
# knob; unrecognised metrics are tolerated (stored for future use)
# but don't change sim behaviour.
KNOWN_METRICS = frozenset({
    "compute_usd_per_day",
    "revenue_usd_per_effective_piece",
    "revenue_quality",
    "revenue_cadence_days",
    "diminishing_k",
})


def apply_calibration(
    *,
    sim_world,
    revenue_model,
    dataset: CalibrationDataset,
) -> dict:
    """Mutate ``sim_world`` and ``revenue_model`` in place from the
    most-recent value per metric. Returns a summary describing which
    knobs were overridden so a test or operator can assert
    deterministically.

    The overrides are applied to the sim's *constants*, not to a
    running Darwin's wallet — calibration changes what the *next*
    eval-harness scenario is scored against."""
    summary: dict = {}
    for metric in KNOWN_METRICS:
        point = dataset.latest(metric)
        if point is None:
            continue
        if metric == "compute_usd_per_day":
            sim_world._compute_rate = point.value / 86_400.0  # noqa: SLF001
        elif metric == "revenue_usd_per_effective_piece":
            revenue_model.usd_per_effective_piece = point.value
        elif metric == "revenue_quality":
            revenue_model.quality = point.value
        elif metric == "revenue_cadence_days":
            revenue_model.cadence_days = point.value
        elif metric == "diminishing_k":
            revenue_model.diminishing_k = point.value
        summary[metric] = {
            "value": point.value,
            "source": point.source,
            "observed_at": point.observed_at,
        }
    return summary


def extract_from_billing(
    billing_summary: dict,
    *,
    source: str = "billing:fleet",
) -> CalibrationDataset:
    """Build a calibration dataset from the supervisor's billing
    summary. Computes a per-day compute rate from the fleet's
    metered_gross + a per-effective-piece revenue estimate from the
    harvest history."""
    ds = CalibrationDataset()
    total = billing_summary.get("total", {})
    metered_gross = float(total.get("metered_gross_usdc", 0.0))
    # The billing summary doesn't directly carry "days observed", so
    # we use ``observed_at = now`` as the timestamp. A richer
    # calibration would pull from per-Darwin spawned_at + last
    # billing record ts for a real rate.
    if metered_gross > 0:
        # Very rough: spread the gross over a 30-day window.
        ds.add(
            metric="compute_usd_per_day",
            value=metered_gross / 30.0,
            source=source,
        )
    return ds
